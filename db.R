make_pool <- function() {
  
  keys <- c("PGHOST", "PGDATABASE", "PGUSER", "PGPASSWORD")
  missing <- keys[!nzchar(Sys.getenv(keys))]
  
  if (length(missing)) {
    stop(
      "Missing environment variables: ",
      paste(missing, collapse = ", ")
    )
  }
  
  pool::dbPool(
    drv = RPostgres::Postgres(),
    host = Sys.getenv("PGHOST"),
    port = as.integer(Sys.getenv("PGPORT", "5432")),
    dbname = Sys.getenv("PGDATABASE"),
    user = Sys.getenv("PGUSER"),
    password = Sys.getenv("PGPASSWORD"),
    sslmode = "require",
    minSize = 0,
    maxSize = 5,
    idleTimeout = 60000
  )
}



query_con <- function(con, sql, params = NULL) {
  if (is.null(params) || !length(params)) return(DBI::dbGetQuery(con, sql))
  DBI::dbGetQuery(con, sql, params = params)
}

exec_con <- function(con, sql, params = NULL) {
  if (is.null(params) || !length(params)) return(DBI::dbExecute(con, sql))
  DBI::dbExecute(con, sql, params = params)
}

db_query <- function(p, sql, params = NULL) {
  con <- pool::poolCheckout(p)
  on.exit(pool::poolReturn(con), add = TRUE)
  query_con(con, sql, params)
}

exec <- function(p, sql, params = NULL) {
  con <- pool::poolCheckout(p)
  on.exit(pool::poolReturn(con), add = TRUE)
  exec_con(con, sql, params)
}

# Validate an existing Neon schema. Never modify tables on application startup.
init_db <- function(p) {
  expected <- list(
    studies = c('study_id','title','publication_year','first_author','doi','url','country','study_design','total_sample','male_n','female_n','other_gender_n','created_at','updated_at'),
    study_groups = c('group_id','study_id','group_name','group_type','group_order'),
    measurements = c('measurement_id','outcome','measurement_tool','domain','self_reported','validated','validation_url','study_ids','created_at'),
    results = c('result_id','study_id','predictor_measurement_id','outcome_measurement_id','df','beta','r','unstandardized_coefficient','p_value','effect_size','effect_size_type','created_at'),
    result_measurement_groups = c('result_measurement_group_id','result_id','measurement_id','group_id','mean','sd','n'),
    correlations = c('correlation_id','study_id','variable_1','variable_2','correlation','created_at'),
    qualitative = c('qualitative_id','study_id','theme','theme_description','created_at')
  )
  con <- pool::poolCheckout(p)
  on.exit(pool::poolReturn(con), add = TRUE)
  for (tbl in names(expected)) {
    if (!DBI::dbExistsTable(con, tbl)) stop('Missing Neon table: ', tbl)
    absent <- setdiff(expected[[tbl]], DBI::dbListFields(con, tbl))
    if (length(absent)) stop('Missing columns in ', tbl, ': ', paste(absent, collapse=', '))
  }
  for (tbl in c('app_users', 'audit_log')) {
    if (!DBI::dbExistsTable(con, tbl)) stop('Missing authentication table: ', tbl)
  }
  invisible(TRUE)
}

# BIGSERIAL ids are generated by PostgreSQL; never generate string IDs.
parse_id <- function(x) {
  if (is.null(x) || !length(x) || !nzchar(trimws(as.character(x)))) return(NULL)
  x <- trimws(as.character(x))
  if (!grepl('^[0-9]+$', x)) stop('ID must be a positive numeric database ID.')
  x
}


num_or_na <- function(x) {
  
  if (
    length(x) == 0 ||
    is.na(x) ||
    !is.finite(x)
  ) {
    return(NA_real_)
  }
  
  as.numeric(x)
}

int_or_na <- function(x) {
  
  if (
    length(x) == 0 ||
    is.na(x) ||
    !is.finite(x)
  ) {
    return(NA_integer_)
  }
  
  as.integer(x)
}



fetch_all <- function(p, table) {
  
  allowed_tables <- c(
    "studies",
    "study_groups",
    "measurements",
    "results",
    "result_measurement_groups",
    "correlations",
    "qualitative"
  )
  
  if (!table %in% allowed_tables) {
    stop("Invalid table name: ", table)
  }
  
  # Check available columns
  con <- pool::poolCheckout(p)
  
  on.exit(
    pool::poolReturn(con),
    add = TRUE
  )
  
  fields <- DBI::dbListFields(con, table)
  
  # Determine ordering column
  order_col <- if ("updated_at" %in% fields) {
    "updated_at"
  } else if ("created_at" %in% fields) {
    "created_at"
  } else {
    NULL
  }
  
  sql <- paste0("SELECT * FROM ", table)
  
  if (!is.null(order_col)) {
    sql <- paste0(
      sql,
      " ORDER BY ",
      order_col,
      " DESC"
    )
  }
  
  DBI::dbGetQuery(con, sql)
}



`%||%` <- function(x, y) {
  if (is.null(x) || length(x) == 0) y else x
}

lookup_doi <- function(value) {
  
  doi <- regmatches(
    value,
    regexpr(
      "10\\.[0-9]{4,9}/[^[:space:]?#]+",
      value,
      perl = TRUE
    )
  )
  
  if (!length(doi) || !nzchar(doi)) {
    stop("No DOI found. Enter metadata manually.")
  }
  
  url <- paste0(
    "https://api.crossref.org/works/",
    utils::URLencode(doi, reserved = TRUE)
  )
  
  r <- httr::GET(
    url,
    httr::timeout(12)
  )
  
  httr::stop_for_status(r)
  
  x <- httr::content(
    r,
    as = "parsed",
    type = "application/json"
  )$message
  
  list(
    doi = doi,
    title = x$title[[1]] %||% "",
    year = x$published[["date-parts"]][[1]][[1]] %||% NA_integer_,
    first_author = x$author[[1]]$family %||% ""
  )
}



parse_matrix <- function(txt) {
  
  sep <- if (grepl("\t", txt)) "\t" else ","
  
  d <- utils::read.table(
    text = txt,
    sep = sep,
    header = TRUE,
    row.names = 1,
    check.names = FALSE,
    fill = TRUE,
    na.strings = c("", "NA"),
    quote = '"',
    comment.char = "",
    strip.white = TRUE
  )
  
  m <- as.matrix(d)
  storage.mode(m) <- "numeric"
  
  if (
    nrow(m) != ncol(m) ||
    !setequal(rownames(m), colnames(m))
  ) {
    stop(
      "Matrix must be square with identical row and column labels."
    )
  }
  
  m <- m[, rownames(m), drop = FALSE]
  
  if (any(!is.na(m) & (m < -1 | m > 1))) {
    stop(
      "Correlation values must be between -1 and 1."
    )
  }
  
  for (i in seq_len(nrow(m))) {
    
    for (j in seq_len(ncol(m))) {
      
      if (is.na(m[i, j]) && !is.na(m[j, i])) {
        m[i, j] <- m[j, i]
      }
      
      if (
        !is.na(m[i, j]) &&
        !is.na(m[j, i]) &&
        abs(m[i, j] - m[j, i]) > 1e-6
      ) {
        stop("Matrix is not symmetric.")
      }
      
    }
  }
  
  m
}

# Extraction writes must use the same connection and transaction as the audit context.
with_reviewer_transaction <- function(p, user_id, fun) {
  id <- as.character(user_id)
  if (length(id) != 1L || is.na(id) || !grepl("^[0-9]+$", id)) {
    stop("A valid authenticated reviewer ID is required.")
  }

  con <- pool::poolCheckout(p)
  on.exit(pool::poolReturn(con), add = TRUE)

  DBI::dbWithTransaction(con, {
    reviewer <- query_con(con,
      "SELECT user_id FROM app_users WHERE user_id = $1 AND status = 'active' FOR SHARE",
      list(id))
    if (nrow(reviewer) != 1L) stop("Reviewer account is not active.")
    query_con(con, "SELECT set_config('app.user_id', $1, true) AS reviewer_id", list(id))
    fun(con)
  })
}
